'use strict';
/* ==========================================================================
   השלמת יומן ב-mode:reset
   --------------------------------------------------------------------------
   ב-reset הלקוח קורא את השיחה מהדיסק (מקור האמת למה שכבר הסתיים). היומן
   בזיכרון עדיין מחזיק את פריימי התור האחרון גם אחרי שהוא נכתב לדיסק — כי
   האיפוס שלו קורה רק בתחילת התור הבא. שידור מחדש של כל היומן אחרי טעינה
   מהדיסק היה מצרף שוב user_msg / stream → הודעות כפולות ברענון.

   לכן ב-reset משלימים מהיומן רק כשיש תור רץ עכשיו (מכשיר שנכנס באמצע),
   ומתחילים מ-user_msg האחרון — תחילת התור החי — כדי לא לשחזר תורות שכבר
   בדיסק אם היומן צבר יותר מתור אחד.
   ========================================================================== */

/**
 * מאיזה seq להשלים ב-mode:reset, או null לדלג (הלקוח נשען על הדיסק).
 * replayLog שולח פריימים עם seq > since.
 */
function resetReplaySince(session) {
  if (!session || !session.running) return null;
  let since = 0;
  for (const frame of session.log || []) {
    if (frame && frame.kind === 'user_msg') {
      const seq = Number(frame.seq) || 0;
      if (seq > 0) since = seq - 1;
    }
  }
  return since;
}

module.exports = { resetReplaySince };
